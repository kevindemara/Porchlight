import { test, expect } from '@playwright/test'
import { enterWorkspace } from './session'

test('guided setup preserves unavailable states and saves only explicit storage choices', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    Object.defineProperty(Notification, 'requestPermission', { value: async () => { throw new Error('Permission must require a pairing action') } })
  })
  await enterWorkspace(page)
  const initial = await (await page.request.get('/api/v1/settings')).json()
  const writes: string[] = []
  page.on('request', request => { if (request.url().includes('/api/v1/') && !['GET', 'HEAD'].includes(request.method())) writes.push(new URL(request.url()).pathname) })
  await page.getByRole('navigation').getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Open setup guide', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Privacy and your local owner' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Choose local storage' })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Storage setup', exact: true })).toBeFocused()
  const budget = page.getByLabel('Archive budget (GiB)')
  await budget.fill(String(initial.archive_budget_gib + 1))
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect.poll(async () => (await (await page.request.get('/api/v1/settings')).json()).archive_budget_gib).toBe(initial.archive_budget_gib + 1)
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Blink cameras', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Recording source and entitlement' })).toBeVisible()
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Local AI', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phone access and permissions' })).toBeVisible()
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Readiness review', exact: true })).toBeVisible()
  await expect(page.getByText('Skipped this visit:', { exact: false })).toContainText('Blink, Recording source, Local AI, Phone')
  await expect(page.getByText('Automatic AI: paused · automatic cleanup: paused.', { exact: false })).toBeVisible()
  expect(writes).toEqual(['/api/v1/settings'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('setup-review.png'), fullPage: true })
  await page.getByRole('button', { name: 'Return to Settings', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open setup guide', exact: true })).toBeFocused()
  await expect(page.getByLabel('Archive budget (GiB)')).toHaveValue(String(initial.archive_budget_gib + 1))
  await page.getByLabel('Archive budget (GiB)').fill(String(initial.archive_budget_gib))
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await expect(page.getByText('Settings saved.', { exact: true })).toBeVisible()
})
