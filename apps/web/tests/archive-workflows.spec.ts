import { test, expect } from '@playwright/test'
import { enterWorkspace as signIn } from './session'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('archive filters, owner correction, digest and confirmed local deletion', async ({ page }, info) => {
  const directory = mkdtempSync(join(tmpdir(), 'porchlight-archive-flow-'))
  const video = join(directory, 'generated.mp4')
  execFileSync(join(process.env.LOCALAPPDATA!, 'Porchlight/tools/ffmpeg/bin/ffmpeg.exe'), ['-v', 'error', '-nostdin', '-f', 'lavfi', '-i', 'color=c=orange:s=320x240:d=1', '-c:v', 'mpeg4', '-y', video])
  try {
    await signIn(page)
    const session = await (await page.request.get('/api/v1/auth/session')).json()
    const response = await page.request.post('/api/v1/imports', { headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': session.csrf_token, 'Content-Type': 'video/mp4', 'X-Recorded-At': '2026-10-07T12:00:00Z' }, data: readFileSync(video) })
    expect(response.status()).toBe(201)
    const event = await response.json()
    await page.getByRole('link', { name: 'Activity', exact: true }).click()
    await page.getByRole('button', { name: /Imported recording/ }).first().click()
    await page.getByLabel('Your description').fill('Reviewed synthetic porch clip')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Close recording' }).click()
    await page.getByLabel('Search recordings', { exact: true }).fill('Reviewed synthetic porch clip')
    await expect(page.getByRole('button', { name: /Reviewed synthetic porch clip/ })).toBeVisible()
    await page.getByText(/^Saved views/).click()
    await page.getByLabel('Saved view name', { exact: true }).fill('Synthetic reviewed view')
    await page.getByRole('button', { name: 'Save current view', exact: true }).click()
    await page.getByRole('button', { name: 'Synthetic reviewed view', exact: true }).click()
    await expect(page).toHaveURL(/#search\?view=/)
    await page.reload()
    await expect(page.getByLabel('Search recordings', { exact: true })).toHaveValue('Reviewed synthetic porch clip')
    await page.getByRole('button', { name: /Reviewed synthetic porch clip/ }).first().click()
    await expect(page).toHaveURL(/#search\?view=.*&event=/)
    await page.reload()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.getByLabel('Your description')).toHaveValue('Reviewed synthetic porch clip')
    await page.getByRole('button', { name: 'Close recording' }).click()
    await page.getByLabel('Search recordings', { exact: true }).fill('Reviewed synthetic porch clip')
    await page.getByText('Filters', { exact: true }).click()
    await page.getByRole('combobox', { name: 'Observed category', exact: true }).selectOption('vehicle')
    await expect(page.getByRole('heading', { name: 'No matching recordings' })).toBeVisible()
    await page.getByRole('button', { name: 'Clear filters' }).click()
    await page.getByRole('link', { name: 'Activity', exact: true }).click()
    await page.getByText('Daily digest', { exact: true }).click()
    await page.getByLabel(/^Day /).fill('2026-10-07')
    await page.getByRole('button', { name: 'Show digest' }).click()
    await expect(page.getByText(/Continuous monitoring/)).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('archive-review.png'), fullPage: true })
    await page.getByRole('button', { name: /Reviewed synthetic porch clip/ }).first().click()
    await page.getByRole('button', { name: 'Delete local recording', exact: true }).click()
    await expect(page.getByText('Delete this local recording?', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Keep recording' }).click()
    expect((await page.request.get(`/api/v1/events/${event.id}`)).status()).toBe(200)
    await page.getByRole('button', { name: 'Delete local recording', exact: true }).click()
    await page.getByRole('button', { name: 'Delete local recording', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect((await page.request.get(`/api/v1/events/${event.id}`)).status()).toBe(404)
    await page.getByRole('link', { name: 'Settings', exact: true }).click()
    await page.getByLabel('Keep ordinary recordings for (days)', { exact: true }).fill('3650')
    await page.getByRole('button', { name: 'Preview local cleanup' }).click()
    await expect(page.getByText('Review before deleting', { exact: true })).toBeVisible()
    await expect(page.getByText(/favourites and.*active items are protected/)).toBeVisible()
    await page.screenshot({ path: info.outputPath('cleanup-preview.png'), fullPage: true })
    await page.getByRole('button', { name: 'Cancel cleanup' }).click()
    await expect(page.getByText('Review before deleting', { exact: true })).toHaveCount(0)
    expect((await (await page.request.get('/api/v1/settings')).json()).retention_enabled).toBe(false)
  } finally { rmSync(directory, { recursive: true, force: true }) }
})

