test('JPEG import shows a protected still image, supports notes, download and confirmed deletion', async ({ page }, info) => {
  const directory = mkdtempSync(join(tmpdir(), 'porchlight-image-flow-'))
  const image = join(directory, 'generated.jpg')
  execFileSync(join(process.env.LOCALAPPDATA!, 'Porchlight/tools/ffmpeg/bin/ffmpeg.exe'), ['-v', 'error', '-nostdin', '-f', 'lavfi', '-i', 'color=c=blue:s=320x240', '-frames:v', '1', '-c:v', 'mjpeg', '-y', image])
  try {
    await signIn(page)
    await page.getByRole('link', { name: 'Activity', exact: true }).click()
    await page.getByLabel('Choose an MP4 recording or JPEG image', { exact: true }).setInputFiles({ name: 'generated.jpg', mimeType: 'image/jpeg', buffer: readFileSync(image) })
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    const still = dialog.getByRole('img', { name: 'Imported image', exact: true })
    await expect(still).toBeVisible()
    await expect.poll(() => still.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBe(320)
    await expect(dialog.locator('video')).toHaveCount(0)
    await expect(dialog.getByRole('link', { name: 'Download original' })).toHaveAttribute('download', /\.jpg$/)
    await page.getByLabel('Your notes').fill('Synthetic still image review')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.getByText('Saved.', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('image-review.png') })
    await page.getByRole('button', { name: 'Delete local recording', exact: true }).click()
    await page.getByRole('button', { name: 'Delete local recording', exact: true }).click()
    await expect(dialog).toHaveCount(0)
  } finally { rmSync(directory, { recursive: true, force: true }) }
})
