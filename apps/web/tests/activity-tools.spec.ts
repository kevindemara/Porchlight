import { test, expect } from '@playwright/test'
import { enterWorkspace } from './session'

test('compact Activity tools retain filters, preview AI search and preserve legacy links', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await enterWorkspace(page)
  const requests: URL[] = []
  const recording = { id: 'd4d08d32-aa3e-46e0-8af6-4c57e81491fb', source_type: 'manual_import', captured_at: '2026-10-08T12:00:00Z', discovered_at: '2026-10-08T12:01:00Z', timestamp_quality: 'manual', analysis_status: 'analyzed', summary: 'A vehicle passes the synthetic porch.', ai_summary: 'A vehicle passes the synthetic porch.', corrected_summary: null, labels_source: 'ai', recognized_people: [], favourite: false, note: '', duration_seconds: 10, media_type: 'video/mp4', historical: false, object_categories: ['vehicle'], media_id: null }
  await page.route('**/api/v1/events?*', route => {
    requests.push(new URL(route.request().url()))
    return route.fulfill({ json: { items: [recording], next_cursor: null } })
  })
  // Synthetic interpretation: tests interaction without launching private/local inference.
  await page.route('**/api/v1/search/interpret', route => route.fulfill({ json: { filters: { query: '', favourites: false, categories: ['vehicle'], color: 'white', daypart: 'evening' }, timezone: 'America/Toronto', needs_clarification: false, message: 'Review these synthetic filters.' } }))
  await page.getByRole('link', { name: 'Activity', exact: true }).click()
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav.getByRole('link', { name: 'Search', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: recording.summary })).toBeVisible()
  const toolbar = page.getByRole('region', { name: 'Activity search tools', exact: true })
  for (const label of ['Filters', 'AI search', 'Saved views', 'Daily digest']) await expect(toolbar.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-expanded', 'false')
  const box = await toolbar.boundingBox()
  expect(box!.height).toBeLessThan(info.project.name.includes('phone') ? 240 : info.project.name === 'tablet' ? 165 : 145)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('activity-compact.png'), fullPage: true })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await page.screenshot({ path: info.outputPath('activity-compact-dark.png'), fullPage: true })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })

  const filters = toolbar.getByRole('button', { name: 'Filters', exact: true })
  await filters.focus()
  await page.keyboard.press('Enter')
  await expect(filters).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('combobox', { name: 'Observed category', exact: true }).selectOption('vehicle')
  await page.getByRole('button', { name: 'Filters · 1', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Observed category', exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: 'Remove Category: vehicle', exact: true })).toBeVisible()
  await expect.poll(() => requests.at(-1)?.searchParams.get('category')).toBe('vehicle')
  await page.getByRole('button', { name: 'Remove Category: vehicle', exact: true }).click()
  await expect.poll(() => requests.at(-1)?.searchParams.has('category')).toBe(false)

  await toolbar.getByRole('button', { name: 'AI search', exact: true }).click()
  await page.getByLabel('Describe your search', { exact: true }).fill('white vehicles yesterday evening')
  await page.getByRole('button', { name: 'Preview filters', exact: true }).click()
  await expect(page.getByText('Review these synthetic filters.', { exact: true })).toBeVisible()
  expect(requests.at(-1)?.searchParams.has('color')).toBe(false)
  await page.getByRole('button', { name: 'Apply proposed filters', exact: true }).click()
  await expect.poll(() => requests.at(-1)?.searchParams.get('color')).toBe('white')
  await expect.poll(() => requests.at(-1)?.searchParams.getAll('categories')).toEqual(['vehicle'])
  // Editing one manual field keeps the other accepted AI filters intact.
  await toolbar.getByRole('button', { name: 'Filters · 3', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Observed colour', exact: true })).toHaveValue('white')
  await page.getByRole('combobox', { name: 'Observed direction', exact: true }).selectOption('left_to_right')
  await expect.poll(() => requests.at(-1)?.searchParams.get('color')).toBe('white')
  await expect.poll(() => requests.at(-1)?.searchParams.getAll('categories')).toEqual(['vehicle'])
  await expect.poll(() => requests.at(-1)?.searchParams.get('daypart')).toBe('evening')
  await toolbar.getByRole('button', { name: 'Filters · 4', exact: true }).click()
  // The AI draft remains available after switching panels.
  await toolbar.getByRole('button', { name: 'AI search', exact: true }).click()
  await expect(page.getByLabel('Describe your search', { exact: true })).toHaveValue('white vehicles yesterday evening')
  await toolbar.getByRole('button', { name: 'AI search', exact: true }).click()
  await expect(page.getByLabel('Describe your search', { exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: 'Remove Time of day: evening' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('activity-active-filters.png'), fullPage: true })
  await page.getByRole('button', { name: 'Remove Colour: white' }).click()
  await expect.poll(() => requests.at(-1)?.searchParams.has('color')).toBe(false)
  await expect.poll(() => requests.at(-1)?.searchParams.getAll('categories')).toEqual(['vehicle'])
  await page.getByRole('button', { name: 'Clear all', exact: true }).click()
  await expect(page.getByLabel('Active search filters', { exact: true })).toHaveCount(0)

  await toolbar.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByLabel('Saved view name', { exact: true }).fill('Toolbar draft')
  await toolbar.getByRole('button', { name: 'Daily digest', exact: true }).click()
  await expect(page.getByLabel('Saved view name', { exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: 'Show digest', exact: true })).toBeVisible()
  await toolbar.getByRole('button', { name: 'Saved views', exact: true }).click()
  await expect(page.getByLabel('Saved view name', { exact: true })).toHaveValue('Toolbar draft')
  await page.goto('/#search')
  await expect(page).toHaveURL(/#activity$/)
  await expect(page.getByRole('heading', { name: 'Activity', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
