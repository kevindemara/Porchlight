import { test, expect } from '@playwright/test'
import { enterWorkspace } from './session'

test('simplified navigation preserves legacy links and keeps device changes explicit', async ({ page }, info) => {
  const camera = { id: '00000000-0000-4000-8000-000000000091', name: 'Synthetic entrance', family: 'doorbells', network_name: 'Synthetic home', network_id: 'synthetic-home', observed_armed: true, observed_motion: true, network_control: true, motion_control: true, recording_access: 'cloud_archived', live_view: 'experimental' }
  await page.route('**/api/v1/cameras', route => route.fulfill({ json: { items: [camera] } }))
  await page.route('**/api/v1/cameras/*/commands/latest*', route => route.fulfill({ json: null }))
  await enterWorkspace(page)
  const credit = page.locator('footer').getByRole('link', { name: 'Kevin DeMara', exact: true })
  await credit.scrollIntoViewIfNeeded()
  await expect(credit).toBeVisible()
  await expect(credit).toHaveAttribute('href', 'https://github.com/kevindemara')
  await expect(credit).toHaveAttribute('rel', 'noopener noreferrer')
  await page.screenshot({ path: info.outputPath('github-footer-credit.png'), fullPage: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  const writes: string[] = []
  page.on('request', request => { if (request.url().includes('/api/v1/') && !['GET', 'HEAD'].includes(request.method())) writes.push(new URL(request.url()).pathname) })
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link')).toHaveText(['Live View', 'Activity', 'Faces', 'Settings'])
  await expect(page.getByRole('button', { name: 'Network controls · Armed', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Disarm network', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Camera management', exact: true })).not.toBeVisible()
  await page.goto('/#cameras')
  await expect(page).toHaveURL(/#live\?manage=1$/)
  await expect(page.getByRole('region', { name: 'Camera management', exact: true })).toBeVisible()
  await expect(page.getByText('Recording access verified', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Manage cameras', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Camera management', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Network controls · Armed', exact: true })).toBeVisible()
  await page.goto('/#library')
  await expect(page).toHaveURL(/#activity$/)
  await expect(page.getByRole('group', { name: 'Activity media type' })).toBeVisible()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Review setup', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Setup guide', exact: true })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Settings sections' }).getByRole('button')).toHaveText(['Cameras & recording', 'AI', 'Storage', 'Notifications', 'Appearance', 'Diagnostics'])
  await page.getByRole('button', { name: 'Appearance', exact: true }).click()
  await page.getByLabel('Timezone', { exact: true }).fill('America/Vancouver')
  await page.getByRole('button', { name: 'AI', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Local AI', exact: true })).toBeVisible()
  await expect(page.getByLabel('Timezone', { exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: 'Appearance', exact: true }).click()
  await expect(page.getByLabel('Timezone', { exact: true })).toHaveValue('America/Vancouver')
  expect((await (await page.request.get('/api/v1/settings')).json()).timezone).not.toBe('America/Vancouver')
  expect(writes).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('settings-sections.png'), fullPage: true })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await page.screenshot({ path: info.outputPath('settings-sections-dark.png'), fullPage: true })
  await page.goto('/#settings?section=storage')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Local archive', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Diagnostics', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Readiness', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Notifications', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phone notifications', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Open notification inbox', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Phone notifications', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Rule name', { exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Notification settings', exact: true }).click()
  await expect(page).toHaveURL(/#settings\?section=notifications$/)
  await expect(page.getByLabel('Rule name', { exact: true })).toBeVisible()
  expect(writes).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('notification-settings.png'), fullPage: true })
})
